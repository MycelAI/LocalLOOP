// Generates an nginx `map` of per-page Content-Security-Policy script hashes
// from the static export in out/. Next.js's static export bootstraps each page
// with a few inline <script> elements (the flight payload differs per page), so
// instead of allowing 'unsafe-inline' for scripts the header for each HTML file
// lists exactly the SHA-256 hashes of the inline scripts that page contains.
// Run after `next build`; the Dockerfile copies the result into the nginx image.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const outDir = join(process.cwd(), 'out');
const target = process.argv[2] || join(process.cwd(), 'csp-script-hashes.conf');

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (full.endsWith('.html')) yield full;
  }
}

const scriptPattern = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
// nginx rejects a single config token longer than ~4 KB ("too long
// parameter"), and Next.js splits its inline RSC payload into a varying number
// of <script> chunks, so long pages can need well over a hundred hashes. Each
// page's hashes are therefore stored in chunks of at most HASHES_PER_VAR, one
// constant variable per chunk, and the page's map entry combines them (nginx
// >= 1.11 evaluates variables inside map values).
export const HASHES_PER_VAR = 40;

export function buildCspConf(outRoot) {
  const pageEntries = [];
  const chunkMaps = [];
  let pages = 0;
  for (const file of walk(outRoot)) {
    const html = readFileSync(file, 'utf8');
    const hashes = new Set();
    for (const match of html.matchAll(scriptPattern)) {
      const attrs = match[1];
      if (/\ssrc=/.test(attrs)) continue;                       // external scripts are covered by 'self'
      if (/type=["']application\/ld\+json["']/.test(attrs)) continue; // data blocks are not executed
      if (!match[2].trim()) continue;
      hashes.add(`'sha256-${createHash('sha256').update(match[2], 'utf8').digest('base64')}'`);
    }
    if (hashes.size === 0) continue;
    const uri = `/${relative(outRoot, file).split('\\').join('/')}`;
    const list = [...hashes];
    if (list.length <= HASHES_PER_VAR) {
      pageEntries.push(`  "${uri}" "${list.join(' ')}";`);
    } else {
      const vars = [];
      for (let i = 0; i < list.length; i += HASHES_PER_VAR) {
        const name = `$csp_p${pages}_${i / HASHES_PER_VAR}`;
        vars.push(name);
        chunkMaps.push(`map $uri ${name} {`, `  default "${list.slice(i, i + HASHES_PER_VAR).join(' ')}";`, '}');
      }
      pageEntries.push(`  "${uri}" "${vars.join(' ')}";`);
    }
    pages += 1;
  }
  const lines = [
    '# Generated by scripts/generate-csp-hashes.mjs — do not edit.',
    'map_hash_bucket_size 512;',
    'map_hash_max_size 4096;',
    'map $uri $csp_script_hashes {',
    '  default "";',
    ...pageEntries,
    '}',
    ...chunkMaps,
    '',
  ];
  return { conf: lines.join('\n'), pages };
}

if (import.meta.main ?? process.argv[1]?.endsWith('generate-csp-hashes.mjs')) {
  const { conf, pages } = buildCspConf(outDir);
  writeFileSync(target, conf);
  console.log(`csp hashes: ${pages} pages -> ${target}`);
}
