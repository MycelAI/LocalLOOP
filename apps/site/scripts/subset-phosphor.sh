# Builds the served Phosphor icon subset from the full upstream copy in
# assets-src/phosphor/ (Phosphor Icons 2.1.2, bold weight, MIT):
#   public/assets/icons/phosphor/bold/Phosphor-Bold.woff2  only the used glyphs
#   public/assets/icons/phosphor/bold/style.css            only the used classes
# "Used" = every ph-* class name found in app/, public/assets/js/ and the
# static HTML under public/ (header partial, protocol mirror index). Re-run
# after adding an icon; tests/smoke.test.cjs fails if one is missing.
# Needs uvx (fonttools + brotli are fetched on demand).
set -euo pipefail

SITE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$SITE/assets-src/phosphor"
OUT="$SITE/public/assets/icons/phosphor/bold"
mkdir -p "$OUT"

# Literal ph-* class names, plus <Card icon="name"> props (Card renders ph-${icon}).
names=$( {
  grep -rhoE "\bph-[a-z0-9-]+" "$SITE/app" "$SITE/public/assets/js" --include=*.jsx --include=*.js
  grep -rhoE "\bph-[a-z0-9-]+" "$SITE/public" --include=*.html
  grep -rhoE 'icon="[a-z0-9-]+"' "$SITE/app" --include=*.jsx | sed -E 's/icon="([a-z0-9-]+)"/ph-\1/'
} | grep -vE "^ph-(bold|fill|light|thin|duotone|regular)$" | sort -u)

css="$OUT/style.css"
{
  echo "/* Phosphor Icons 2.1.2 (MIT), bold weight: subset of assets-src/phosphor/style.css"
  echo "   generated by scripts/subset-phosphor.sh; do not edit by hand. */"
  # @font-face and the .ph-bold base rule: everything before the first icon rule.
  awk '/^\.ph-bold\.ph-/ {exit} {print}' "$SRC/style.css" | sed '1d'
} > "$css"

unicodes=()
missing=0
for name in $names; do
  rule=$(awk -v sel=".ph-bold.$name:before {" '$0 == sel {print; getline; print; getline; print; exit}' "$SRC/style.css")
  if [[ -z "$rule" ]]; then
    echo "unknown Phosphor icon: $name" >&2
    missing=1
    continue
  fi
  printf '%s\n' "$rule" >> "$css"
  code=$(printf '%s' "$rule" | grep -oE '\\[0-9a-f]{4}' | head -1 | tr -d '\\')
  unicodes+=("U+$code")
done
(( missing )) && exit 1

uvx --quiet --with brotli --from fonttools pyftsubset "$SRC/Phosphor-Bold.woff2" \
  --unicodes="$(IFS=,; echo "${unicodes[*]}")" \
  --flavor=woff2 --layout-features='*' --no-hinting \
  --output-file="$OUT/Phosphor-Bold.woff2"

echo "subset: ${#unicodes[@]} icons, $(wc -c < "$OUT/Phosphor-Bold.woff2") bytes font, $(wc -c < "$css") bytes css"
